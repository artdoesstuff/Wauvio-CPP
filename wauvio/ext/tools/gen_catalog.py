#!/usr/bin/env python3
"""Rebuilds instrument_catalog.hpp from wauvio/ext/instruments/**/*.hpp.

Run it after adding or removing an instrument class:   python3 gen_catalog.py
Every `class X : public Base` found there is listed; render_instruments.cpp keeps only the ones that are default-constructible
instruments (or drum kits), so helper/base classes are filtered out at compile time.
"""
import pathlib, re
here = pathlib.Path(__file__).resolve().parent
inst = here.parent / "instruments"
rows = []
for p in sorted(inst.rglob("*.hpp")):
    family = p.parent.name
    for m in re.finditer(r'^\s*class\s+(\w+)\s*:\s*public\s+(\w+)', p.read_text(encoding="utf-8"), re.M):
        rows.append((family, m.group(1), m.group(2)))
out = ["#pragma once", "// GENERATED by gen_catalog.py - do not edit. Re-run it after adding or removing instrument classes.",
       "// X(family, ClassName, BaseName)", "#define WAUVIO_CLASS_CATALOG(X) \\"]
out += [f"    X({f}, {c}, {b}) \\" for f, c, b in rows]
out[-1] = out[-1].rstrip(" \\")
(here / "instrument_catalog.hpp").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(rows)} classes written to instrument_catalog.hpp")
