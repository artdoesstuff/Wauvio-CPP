#pragma once
// voice_gen: build-time generator behind `voice_tool gen`. Identical in every yune-vN/tools folder (V2 and up).
//
// Include it from voice_tool.cpp AFTER the engine header and `using namespace wauvio::vocal::vN;`, because it uses
// VoiceProfile, load_profile, profile_to_text and voice_yune unqualified.
//
// What it does, given a yune-vN folder:
//   voicebanks/<name>.wvc  <->  voices/voice-<name>.hpp     paired by name ("voice-" prefix optional on the .wvc)
//   - a .wvc with a header          paired, nothing to do (the hand-written header is never overwritten without --force)
//   - a .wvc without a header       voices/voice-<name>.hpp is generated (the bank text is embedded and parsed on first use)
//   - a header without a .wvc       kept, reported as code-only
//   - voices/voices_registry.hpp    regenerated from the pairs; it holds the #includes and builtin_voices()
// Generated headers start with a "GENERATED by voice_tool gen" line and are rewritten whenever their .wvc changes.
// Voices must be in the registry to be built in, so rebuild after running it.
#include <algorithm>
#include <cctype>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

namespace voice_gen {
    namespace fs = std::filesystem;

    struct Options {
        fs::path root;          // the yune-vN folder (contains voices/ and voicebanks/)
        std::string ns;         // "v2", "v3", ...
        bool check = false;     // write nothing; exit status 1 if anything is missing or out of date
        bool force = false;     // also replace hand-written headers that have a .wvc with a generated one
    };

    inline const char* kMarker = "// GENERATED by voice_tool gen";

    // "voice-yune-old" / "yune-old" -> "yune-old"
    inline std::string name_of(const fs::path& p) {
        std::string s = p.stem().string();
        return s.rfind("voice-", 0) == 0 ? s.substr(6) : s;
    }
    // "yune-old" -> "voice_yune_old"
    inline std::string ident_of(const std::string& name) {
        std::string o = "voice_";
        for (char c : name) o += std::isalnum(static_cast<unsigned char>(c)) ? c : '_';
        return o;
    }
    inline bool valid_name(const std::string& n) {
        if (n.empty()) return false;
        for (char c : n) if (!(std::isalnum(static_cast<unsigned char>(c)) || c == '-' || c == '_')) return false;
        return true;
    }
    inline bool read_file(const fs::path& p, std::string& out) {
        std::ifstream f(p, std::ios::binary); if (!f) return false;
        std::ostringstream ss; ss << f.rdbuf(); out = ss.str(); return true;
    }
    // Writes only when the content differs. Returns true if the file was (or, with check, would be) changed.
    inline bool write_if_changed(const fs::path& p, const std::string& content, bool check) {
        std::string cur;
        if (read_file(p, cur) && cur == content) return false;
        if (!check) { std::ofstream f(p, std::ios::binary); f << content; }
        return true;
    }

    inline std::string generated_header(const std::string& ns, const std::string& name, const std::string& bank_file,
                                        const std::string& text) {
        std::string delim = "WVC";
        while (text.find(")" + delim + "\"") != std::string::npos) delim += "_";
        std::string o;
        o += std::string(kMarker) + " from voicebanks/" + bank_file + ".\n";
        o += "// Edit the .wvc and run `voice_tool gen` again, or replace this file with a hand-written header (and remove this line).\n";
        o += "#pragma once\n#include \"profile.hpp\"\n\n";
        o += "namespace wauvio {\n    namespace vocal {\n        namespace " + ns + " {\n\n";
        o += "            inline VoiceProfile " + ident_of(name) + "() {\n";
        o += "                static const std::string kBank = std::string()\n";
        // raw string literals are split on line boundaries to stay under compiler literal-length limits (MSVC: 16 KB)
        std::istringstream in(text); std::string line, chunk;
        auto flush = [&] { if (!chunk.empty()) { o += "                    + R\"" + delim + "(" + chunk + ")" + delim + "\"\n"; chunk.clear(); } };
        while (std::getline(in, line)) { chunk += line + "\n"; if (chunk.size() > 6000) flush(); }
        flush();
        o += "                    ;\n";
        o += "                VoiceProfile p; profile_from_text(kBank, p);\n                return p;\n            }\n\n";
        o += "        } // namespace " + ns + "\n    }\n}\n";
        return o;
    }

    struct Entry {
        std::string name;           // pairing name
        std::string key;            // id used in builtin_voices(): always the pairing name
        std::string bank_file;      // stem of the .wvc, empty if none
        bool has_header = false, header_generated = false;
    };

    inline int run(const Options& o) {
        const fs::path voices = o.root / "voices", banks = o.root / "voicebanks";
        if (!fs::is_directory(voices) || !fs::is_directory(banks)) {
            std::fprintf(stderr, "gen: expected %s and %s (pass --root <yune-vN folder>)\n", voices.string().c_str(), banks.string().c_str());
            return 2;
        }
        int errors = 0, changed = 0;
        std::map<std::string, Entry> all;

        for (auto& de : fs::directory_iterator(banks)) {
            if (de.path().extension() != ".wvc") continue;
            Entry& e = all[name_of(de.path())];
            if (!e.bank_file.empty()) { std::fprintf(stderr, "error: %s and %s.wvc pair with the same voice\n", de.path().filename().string().c_str(), e.bank_file.c_str()); ++errors; }
            e.name = name_of(de.path()); e.bank_file = de.path().stem().string();
        }
        for (auto& de : fs::directory_iterator(voices)) {
            const std::string fn = de.path().filename().string();
            if (fn.rfind("voice-", 0) != 0 || de.path().extension() != ".hpp") continue;
            Entry& e = all[name_of(de.path())]; e.name = name_of(de.path()); e.has_header = true;
            std::string txt; read_file(de.path(), txt); e.header_generated = txt.rfind(kMarker, 0) == 0;
        }

        for (auto& kv : all) {
            Entry& e = kv.second;
            if (!valid_name(e.name)) { std::fprintf(stderr, "error: '%s' is not a usable voice name (letters, digits, - and _ only)\n", e.name.c_str()); ++errors; continue; }
            e.key = e.name;
            const fs::path hpp = voices / ("voice-" + e.name + ".hpp");
            if (e.bank_file.empty()) {
                std::printf("code-only  %-12s voices/voice-%s.hpp has no .wvc\n", e.name.c_str(), e.name.c_str());
                if (e.header_generated) std::printf("warning: %s is generated but its .wvc is gone; keeping it\n", hpp.filename().string().c_str());
                continue;
            }
            // load exactly like make_voice() loads a file: over the complete yune base, so partial banks work
            VoiceProfile p = voice_yune(); std::string err;
            const fs::path bank = banks / (e.bank_file + ".wvc");
            if (!load_profile(bank.string(), p, &err)) { std::fprintf(stderr, "error: %s: %s\n", bank.filename().string().c_str(), err.c_str()); ++errors; e.bank_file.clear(); continue; }
            if (p.id != e.name) std::printf("note:      %s has voice id '%s' but pairs as '%s'; the registry key is '%s'\n", bank.filename().string().c_str(), p.id.c_str(), e.name.c_str(), e.name.c_str());
            if (e.has_header && !e.header_generated && !o.force) {
                std::string txt; read_file(hpp, txt);
                if (txt.find(ident_of(e.name) + "(") == std::string::npos) { std::fprintf(stderr, "error: %s does not define %s()\n", hpp.filename().string().c_str(), ident_of(e.name).c_str()); ++errors; }
                std::printf("paired     %-12s\n", e.name.c_str());
                continue;
            }
            const std::string text = profile_to_text(p);
            const bool existed = e.has_header;
            if (write_if_changed(hpp, generated_header(o.ns, e.name, e.bank_file + ".wvc", text), o.check)) {
                ++changed; std::printf("%s  %-12s voices/voice-%s.hpp\n", o.check ? (existed ? "stale     " : "missing   ") : (existed ? "updated   " : "generated "), e.name.c_str(), e.name.c_str());
            } else std::printf("up to date %-12s (generated)\n", e.name.c_str());
            e.has_header = true;
        }

        // registry: "yune" first (it is the base for partial .wvc files), the rest alphabetical
        std::vector<Entry*> order;
        for (auto& kv : all) if (kv.second.has_header) order.push_back(&kv.second);
        std::stable_sort(order.begin(), order.end(), [](Entry* a, Entry* b) { return (a->name == "yune") > (b->name == "yune"); });
        std::string r = std::string(kMarker) + ". It is rebuilt from voices/ and voicebanks/; do not edit it.\n#pragma once\n";
        r += "#include <functional>\n#include <string>\n#include <utility>\n#include <vector>\n";
        for (auto* e : order) r += "#include \"voice-" + e->name + ".hpp\"\n";
        r += "\nnamespace wauvio {\n    namespace vocal {\n        namespace " + o.ns + " {\n\n";
        r += "            inline const std::vector<std::pair<std::string, std::function<VoiceProfile()>>>& builtin_voices() {\n";
        r += "                static const std::vector<std::pair<std::string, std::function<VoiceProfile()>>> v = {\n";
        for (auto* e : order) r += "                    { \"" + e->key + "\", [] { return " + ident_of(e->name) + "(); } },\n";
        r += "                };\n                return v;\n            }\n\n        } // namespace " + o.ns + "\n    }\n}\n";
        if (write_if_changed(voices / "voices_registry.hpp", r, o.check)) { ++changed; std::printf("%s voices/voices_registry.hpp (%zu voices)\n", o.check ? "stale     " : "updated   ", order.size()); }
        else std::printf("up to date voices/voices_registry.hpp (%zu voices)\n", order.size());

        if (errors) { std::fprintf(stderr, "gen: %d error(s)\n", errors); return 1; }
        if (o.check && changed) { std::fprintf(stderr, "gen: %d file(s) out of date; run `voice_tool gen`\n", changed); return 1; }
        if (!o.check && changed) std::printf("done: rebuild to pick up the changes\n");
        return 0;
    }
}
